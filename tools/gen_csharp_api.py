"""Generates managed/Mirage/Native/Api.g.cs from loader/include/mirage/api.h: the MirageApi and MirageUi function tables as
blittable C# structs of unmanaged function pointers, in the C header's order (the ABI is append-only, so appending to
api.h and running this again is all a C# binding needs).

    python tools/gen_csharp_api.py            # writes the file
    python tools/gen_csharp_api.py --check    # exits 1 when the file is out of date (the build runs this)

Types: integers and floats map to their C# equivalents, `const char*` to byte* (UTF-8), every other pointer (handles,
structs, callbacks) to void* / nint. Nothing is marshalled: the managed side passes pointers it pinned or allocated.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "loader" / "include" / "mirage" / "api.h"
OUT = ROOT / "managed" / "Mirage" / "Native" / "Api.g.cs"

SCALARS = {
    "void": "void", "int32_t": "int", "uint32_t": "uint", "int64_t": "long", "uint64_t": "ulong", "int": "int",
    "unsigned": "uint", "float": "float", "double": "double", "size_t": "nuint", "uint8_t": "byte", "int8_t": "sbyte",
    "uint16_t": "ushort", "int16_t": "short", "char": "byte", "bool": "byte",
}


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def map_type(c: str) -> str:
    c = " ".join(c.replace("const ", "").split())
    stars = c.count("*")
    base = c.replace("*", "").strip()
    if stars == 0:
        if base in SCALARS:
            return SCALARS[base]
        # Enums and callbacks typedef'd as values: MirageLogLevel etc. are int-sized; function-pointer typedefs are pointers
        if base.endswith("Fn") or base == "MirageCallback":
            return "void*"
        if base.startswith("Mirage"):
            return "int"
        raise ValueError(f"unknown type {c!r}")
    if base in ("char",) and stars == 1:
        return "byte*"
    return "void*" if stars == 1 else "void**"


def param_type(p: str) -> str:
    p = p.strip()
    if not p or p == "void":
        return ""
    # Drop the parameter name: the last identifier, unless the declaration is only a type
    m = re.match(r"^(.*?[\s\*])(\w+)$", p)
    ctype = m.group(1) if m else p
    return map_type(ctype)


def table(text: str, name: str) -> list[tuple[str, str, list[str]]]:
    m = re.search(r"typedef struct " + name + r"\s*\{(.*?)\}\s*" + name + r"\s*;", text, flags=re.S) or         re.search(r"(?<!typedef )struct " + name + r"\s*\{(.*?)\}\s*;", text, flags=re.S)
    if not m:
        raise ValueError(f"{name} not found")
    body = m.group(1)
    fields = []
    for decl in body.split(";"):
        decl = " ".join(decl.split())
        if not decl:
            continue
        f = re.match(r"^(.*?)\(\s*MIRAGE_CALL\s*\*\s*(\w+)\s*\)\s*\((.*)\)$", decl)
        if f:
            ret, fname, params = f.group(1), f.group(2), f.group(3)
            args = [param_type(p) for p in params.split(",")] if params.strip() not in ("", "void") else []
            args = [a for a in args if a]
            fields.append((fname, map_type(ret), args))
            continue
        plain = re.match(r"^(.*?)(\w+)$", decl)
        if plain:
            fields.append((plain.group(2), map_type(plain.group(1)), None))
            continue
        raise ValueError(f"can't read: {decl}")
    return fields


def emit(name: str, fields) -> str:
    lines = [f"    [StructLayout(LayoutKind.Sequential)]", f"    public unsafe struct {name}", "    {"]
    for fname, ret, args in fields:
        if args is None:
            lines.append(f"        public {ret} {fname};")
        else:
            sig = ", ".join(args + [ret])
            lines.append(f"        public delegate* unmanaged[Cdecl]<{sig}> {fname};")
    lines.append("    }")
    return "\n".join(lines)


def generate() -> str:
    text = strip_comments(HEADER.read_text(encoding="utf-8"))
    parts = [
        "// <auto-generated> by tools/gen_csharp_api.py from loader/include/mirage/api.h: do not edit. Run it again after api.h changes.",
        "#pragma warning disable CS8500, IDE1006",
        "using System.Runtime.InteropServices;",
        "",
        "namespace Mirage.Native",
        "{",
        emit("MirageApi", table(text, "MirageApi")),
        "",
        emit("MirageUi", table(text, "MirageUi")),
        "}",
        "",
    ]
    return "\n".join(parts)


def main() -> int:
    out = generate()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != out:
            print(f"{OUT} is out of date: run python tools/gen_csharp_api.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
