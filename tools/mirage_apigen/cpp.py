"""Generate package-local registrations for reviewed Lua contracts."""

from __future__ import annotations

from collections import defaultdict

from .render import PublicFunction


def cpp(functions: list[PublicFunction]) -> dict[str, str]:
    packages: dict[str, list[PublicFunction]] = defaultdict(list)
    for fn in functions:
        packages[fn.source.partition(".")[0]].append(fn)
    files = {}
    for pkg, items in sorted(packages.items()):
        lines = ['// Generated by MirageAPIGen.', '#include "runtime/lua/lua_functions.h"', "",
                 "namespace mirage::mods", "{", "\tnamespace", "\t{"]
        registrations = []
        emitted: dict[tuple[str, str, str], str] = {}
        for fn in items:
            key = (fn.source, fn.operation, fn.cpp_type)
            if fn.wrapper:
                target = f"sdk_binding::{fn.wrapper}"
            elif key in emitted:
                target = emitted[key]
            else:
                owner, _, member = fn.source.rpartition(".")
                operation = "Read" if fn.operation == "get" else "Write"
                target = f"Bind{len(emitted)}"
                emitted[key] = target
                lines.extend((f"\t\tint {target}(lua_State* L)", "\t\t{",
                              f'\t\t\treturn sdk_binding::{operation}(L, "Class {owner}", "{member}", {fn.cpp_type});',
                              "\t\t}", ""))
            registrations.append(f'\t\t\t{{"{fn.name}", {target}}},')
        lines.extend(('\t\tconst LuaFunctions kFunctions("sdk", {', *registrations, "\t\t});", "\t}", "}", ""))
        files[f"cpp/package-{pkg}.cpp"] = "\n".join(lines)
    return files
