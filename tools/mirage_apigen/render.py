"""Render the public contract and separate SDK inspection definitions."""

from __future__ import annotations

from collections import defaultdict
from collections.abc import Iterable
from dataclasses import dataclass

from .analysis import APIModule, TypeResolver
from .config import KEYWORDS, lua_identifier
from .sdk import SDKClass, SDKEnum

LUA_HEADER = "---@meta\n-- Generated by MirageAPIGen.\n\n"


@dataclass(frozen=True, slots=True)
class PublicFunction:
    name: str
    source: str
    parameters: tuple[tuple[str, str, bool], ...]
    returns: tuple[tuple[str, str], ...]
    deprecated: bool
    experimental: bool
    description: str
    wrapper: str
    operation: str = ""
    cpp_type: str = ""

    def signature(self) -> dict:
        return {"source": self.source, "parameters": self.parameters, "returns": self.returns,
                "deprecated": self.deprecated, "experimental": self.experimental, "game_thread": True}


def public_functions(api: APIModule) -> Iterable[PublicFunction]:
    receiver = (("object", "MirageAPIGen.Object", False),)
    for cls in api.classes.values():
        for prop in cls.properties:
            source = f"{cls.path}.{prop.source.name}"
            for name in prop.names:
                yield PublicFunction(f"get_{name}", source, receiver, (("", f"{prop.binding.lua_type}|nil"),),
                                     prop.rule.deprecated, prop.rule.experimental, prop.rule.description,
                                     prop.binding.wrapper, "get", prop.binding.cpp_type)
                if prop.rule.writable:
                    yield PublicFunction(f"set_{name}", source, (*receiver, ("value", prop.binding.lua_type, False)),
                                         (("", "boolean"),), prop.rule.deprecated, prop.rule.experimental,
                                         prop.rule.description, prop.binding.wrapper, "set", prop.binding.cpp_type)
        for fn in cls.functions:
            args = tuple((lua_identifier(name), kind, optional) for name, kind, direction, optional in fn.signature
                         if direction in ("in", "inout"))
            returns = tuple((lua_identifier(name), kind) for name, kind, direction, _ in
                            sorted(fn.signature, key=lambda p: p[2] != "return") if direction != "in")
            for name in fn.names:
                yield PublicFunction(name, fn.source.path, (*receiver, *args), returns, fn.rule.deprecated,
                                     fn.rule.experimental, fn.rule.description, fn.wrapper)


def _annotations(args: Iterable[tuple[str, str, bool]], results: Iterable[tuple[str, str]]) -> list[str]:
    args = list(args)
    results = list(results)
    overloads = []
    required = len(args)
    while required and args[required - 1][2]:
        required -= 1
        signature = ", ".join(f"{name}: {kind}" for name, kind, _ in args[:required])
        returned = ", ".join(kind for _, kind in results)
        overloads.append(f"---@overload fun({signature})" + (f": {returned}" if returned else ""))
    return [*overloads, *(f"---@param {name}{'?' if optional else ''} {kind}" for name, kind, optional in args),
            *(f"---@return {kind}{' ' + name if name else ''}" for name, kind in results)]


def _lua_description(value: str) -> list[str]:
    # Always prefix comment text, and keep it from becoming an annotation.
    return [f"--- {line}" for line in value.splitlines()]


def luals(functions: list[PublicFunction]) -> str:
    lines = [LUA_HEADER.rstrip(), "", "---@class MirageAPIGen.Object", "",
             "---@class MirageAPIGen.Runtime", "mirage.sdk = {}", ""]
    for fn in functions:
        lines.extend(_lua_description(fn.description))
        lines.append("--- Game thread only.")
        if fn.experimental:
            lines.append("--- Experimental API.")
        if fn.deprecated:
            lines.append("---@deprecated")
        lines.extend(_annotations(fn.parameters, fn.returns))
        args = ", ".join(arg[0] for arg in fn.parameters)
        lines.extend((f"function mirage.sdk.{fn.name}({args}) end", ""))
    return "\n".join(lines) + "\n"


def inspection(api: APIModule, resolver: TypeResolver) -> dict[str, str]:
    packages: dict[str, list[str]] = defaultdict(list)
    for path, info in api.types.items():
        entry = resolver.index.types[path]
        name = info["lua_name"]
        package = path.partition(".")[0]
        # Lua limits a function to 200 locals. Give each declaration its own block.
        symbol = "t"
        block = _lua_description(resolver.policy.descriptions.get(path, ""))
        if isinstance(entry, SDKEnum):
            if entry.values:
                block.extend((f"---@enum {name}", f"local {symbol} = {{"))
                block.extend(f'    ["{key}"] = {value},' for key, value in entry.values.items())
                block.append("}")
            else:
                block.append(f"---@alias {name} integer")
        else:
            parent = resolver.names.get(info["super"])
            block.append(f"---@class {name}" + (f" : {parent}" if parent and info["super"] in api.types else ""))
            for prop in entry.properties:
                full_path = f"{path}.{prop.name}"
                kind, _ = resolver.resolve(prop.type)
                if kind and api.members[full_path]["editor"]:
                    key = f'["{prop.name}"]' if prop.name in KEYWORDS else prop.name
                    block.append(f"---@field {key} {kind}")
            block.append(f"local {symbol} = {{}}")
            if isinstance(entry, SDKClass):
                for fn in entry.functions:
                    signature, _ = resolver.signature(fn)
                    if signature is None or not api.members.get(fn.path, {}).get("editor"):
                        continue
                    name = fn.path.rpartition(".")[2]
                    args = [(f"p{i}_{param}", kind, opt) for i, (param, kind, direction, opt) in enumerate(signature)
                            if direction in ("in", "inout")]
                    results = [(lua_identifier(param), kind) for param, kind, direction, _ in
                               sorted(signature, key=lambda p: p[2] != "return") if direction != "in"]
                    block.append("")
                    arg_names = [arg[0] for arg in args]
                    if fn.flags is None or not fn.flags & 0x2000:  # FUNC_Static as in sdkgen/emit_lua.cpp
                        args.insert(0, ("self", info["lua_name"], False))
                        arg_names.insert(0, "self")
                    block.extend(_annotations(args, results))
                    block.append(f'{symbol}["{name}"] = function({", ".join(arg_names)}) end')
        packages[package].append("\n".join(("do", *("    " + line if line else "" for line in block), "end")))
    return {f"inspection/package-{pkg}.lua": LUA_HEADER + "-- SDK inspection metadata only.\n\n" + "\n\n".join(blocks) + "\n"
            for pkg, blocks in sorted(packages.items())}
