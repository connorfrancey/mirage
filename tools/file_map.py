"""Writes docs/FILE-MAP.md: one line per header (and per CLI module), from its leading comment. Run from the repository
root after adding or renaming files: `python tools/file_map.py`."""
import os
import re

DIRS = ["loader/include/mirage", "loader/src/core", "loader/src/game", "loader/src/runtime", "loader/src/runtime/mem",
        "loader/src/features/misc", "loader/src/tas", "tools/mirage_tools"]


def summary(path: str) -> str:
    """The first two sentences of the file's leading comment ("" if it has none)."""
    lines = open(path, encoding="utf-8", errors="replace").read().splitlines()
    python = path.endswith(".py")
    comment = []
    for line in lines[:30]:
        t = line.strip()
        if not t or t.startswith(("#pragma", "#include", "#!", "from ", "import ")):
            if comment:
                break
            continue
        if t.startswith('"""') and python:
            comment.append(t.strip('"'))
            if t.count('"""') == 2:
                break
        elif t.startswith("//"):
            comment.append(t[2:].strip())
        elif t.startswith("#") and python:
            comment.append(t[1:].strip())
        elif t.startswith(("/*", "*")):
            comment.append(t.strip("/* "))
        elif python and comment:
            comment.append(t.strip('"'))
            if t.endswith('"""'):
                break
        else:
            break
    text = " ".join(c for c in comment if c)
    return " ".join(re.split(r"(?<=[.])\s", text)[:2])[:300]


def main() -> None:
    out = ["# File map", "",
           "One line per header: what the file is, taken from its leading comment. Generated by `python tools/file_map.py`;",
           "read the header itself for the details. See [AI-GUIDE.md](AI-GUIDE.md) first.", ""]
    for d in DIRS:
        if not os.path.isdir(d):
            continue
        rows = [f"- `{d}/{f}`: {s}" for f in sorted(os.listdir(d)) if f.endswith((".h", ".hpp", ".py"))
                if (s := summary(os.path.join(d, f)))]
        if rows:
            out += [f"## {d}", "", *rows, ""]
    with open("docs/FILE-MAP.md", "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
