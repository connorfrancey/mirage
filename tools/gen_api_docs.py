"""Generates docs/api-reference.md from loader/include/mirage/api.h: the mod API's functions (MirageApi, in its order,
grouped by the header's "/* ---- Section" comments) and its types, each with the comment the header gives it. The
header is the source of truth; the Lua binding (mirage.*), the C++ wrappers (mirage/mirage.hpp) and C# (Mirage.Mod)
mirror it.

    python tools/gen_api_docs.py            # writes the file
    python tools/gen_api_docs.py --check    # exits 1 when the file is out of date
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "loader" / "include" / "mirage" / "api.h"
OUT = ROOT / "docs" / "api-reference.md"

TOKEN = re.compile(r"/\*(.*?)\*/|//([^\n]*)|([^;/]+;)", re.S)


def clean_comment(body: str) -> str:
    lines = [re.sub(r"^\s*\*\s?", "", l).rstrip() for l in body.strip().splitlines()]
    return " ".join(l.strip() for l in lines if l.strip())


def squash(code: str) -> str:
    return re.sub(r"\s+", " ", code).replace("( ", "(").replace(" )", ")").strip()


def api_body(text: str) -> str:
    start = text.index("typedef struct MirageApi")
    open_brace = text.index("{", start)
    end = text.index("} MirageApi;", open_brace)
    return text[open_brace + 1:end]


def functions(body: str) -> list[tuple[str, str, list[tuple[str, str, str]]]]:
    """[(section title, section intro, [(name, declaration, comment)])]"""
    sections: list[tuple[str, str, list]] = [("Basics", "", [])]
    pending: list[str] = []
    for m in TOKEN.finditer(body):
        block, line, decl = m.group(1), m.group(2), m.group(3)
        if block is not None or line is not None:
            text = clean_comment(block if block is not None else line)
            if text.startswith("----"):
                text = text.strip("- ")
                title, _, intro = text.partition(". ")
                title = re.split(r"\s*\(|:", title, maxsplit=1)[0].strip(" .-") or "More"
                sections.append((title, intro.strip(" -"), []))
                pending = []
            elif text:
                pending.append(text)
            continue
        code = squash(decl)
        name = re.search(r"\(\s*MIRAGE_CALL\s*\*\s*(\w+)\s*\)", code)
        field = name.group(1) if name else re.findall(r"(\w+)\s*;$", code)[-1]
        sections[-1][2].append((field, code, " ".join(pending)))
        pending = []
    return [s for s in sections if s[2]]


def types(text: str) -> list[tuple[str, str, str]]:
    """[(name, code, comment)] for the header's structs, enums and callback types (not MirageApi)."""
    out = []
    for m in re.finditer(r"(/\*(?:(?!\*/).)*\*/\s*)?(typedef\s+(?:struct|enum)\s+\w+\s*\{.*?\}\s*(\w+)\s*;)", text, re.S):
        name = m.group(3)
        if name == "MirageApi":
            continue
        out.append((name, m.group(2).strip(), clean_comment(m.group(1)[2:-2]) if m.group(1) else ""))
    for m in re.finditer(r"(/\*(?:(?!\*/).)*\*/\s*)?(typedef\s+[\w\s\*]+\(MIRAGE_CALL\s*\*\s*(\w+)\)\s*\([^;]*\)\s*;)", text, re.S):
        out.append((m.group(3), squash(m.group(2)), clean_comment(m.group(1)[2:-2]) if m.group(1) else ""))
    return out


def render() -> str:
    text = HEADER.read_text(encoding="utf-8")
    parts = ["<!-- Generated by tools/gen_api_docs.py from loader/include/mirage/api.h: don't edit, run `mirage docs api` -->",
             "# Mirage mod API reference", "",
             "Every function a mod can call, in `MirageApi`'s order (ABI v1 only grows: entries are appended, never "
             "changed), with what `loader/include/mirage/api.h` says about it. The same API is `mirage.*` in Lua, the "
             "`mirage::` wrappers in C++ (`mirage/mirage.hpp`) and `Mod`, `Module` and `GameObject` in C#. Calls marked "
             "\"game thread\" run from a module's tick, an event or a hook; a newer function is checked with "
             "`MIRAGE_API_HAS(api, field)` when a mod may run on an older runtime.", ""]
    sections = functions(api_body(text))
    parts.append("## Contents")
    parts.append("")
    for title, _, fns in sections:
        anchor = re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")
        parts.append(f"- [{title}](#{anchor}) ({len(fns)})")
    parts.append("- [Types](#types)")
    parts.append("")
    for title, intro, fns in sections:
        parts.append(f"## {title}")
        parts.append("")
        if intro:
            parts.append(intro)
            parts.append("")
        for name, code, comment in fns:
            parts.append(f"### `{name}`")
            parts.append("")
            parts.append("```c")
            parts.append(code)
            parts.append("```")
            parts.append("")
            if comment:
                parts.append(comment)
                parts.append("")
    parts.append("## Types")
    parts.append("")
    for name, code, comment in types(text):
        parts.append(f"### `{name}`")
        parts.append("")
        if comment:
            parts.append(comment)
            parts.append("")
        parts.append("```c")
        parts.append(code)
        parts.append("```")
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def main() -> int:
    content = render()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print(f"{OUT.relative_to(ROOT)} is out of date: run `mirage docs api`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
